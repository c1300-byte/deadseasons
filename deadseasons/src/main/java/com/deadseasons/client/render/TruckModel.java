package com.deadseasons.client.render;

import com.deadseasons.DeadSeasons;
import com.deadseasons.entity.BoxTruckEntity;
import com.mojang.blaze3d.vertex.PoseStack;
import com.mojang.blaze3d.vertex.VertexConsumer;
import net.minecraft.client.model.EntityModel;
import net.minecraft.client.model.geom.ModelLayerLocation;
import net.minecraft.client.model.geom.ModelPart;
import net.minecraft.client.model.geom.PartPose;
import net.minecraft.client.model.geom.builders.CubeListBuilder;
import net.minecraft.client.model.geom.builders.LayerDefinition;
import net.minecraft.client.model.geom.builders.MeshDefinition;
import net.minecraft.client.model.geom.builders.PartDefinition;

/**
 * Box truck: cab at the front (-Z), cargo box behind it, chassis and four wheels.
 * Texture layout (256x256) is generated by tools/make_assets.py.
 */
public class TruckModel extends EntityModel<BoxTruckEntity> {
    public static final ModelLayerLocation LAYER = new ModelLayerLocation(DeadSeasons.id("box_truck"), "main");

    private final ModelPart body;
    private final ModelPart[] wheels;

    public TruckModel(ModelPart root) {
        this.body = root.getChild("body");
        this.wheels = new ModelPart[]{body.getChild("wheel_fl"), body.getChild("wheel_fr"), body.getChild("wheel_bl"), body.getChild("wheel_br")};
    }

    public static LayerDefinition createBodyLayer() {
        MeshDefinition mesh = new MeshDefinition();
        PartDefinition root = mesh.getRoot();
        PartDefinition body = root.addOrReplaceChild("body", CubeListBuilder.create()
                        .texOffs(0, 0).addBox(-20f, -46f, -10f, 40f, 36f, 54f)    // cargo box
                        .texOffs(0, 90).addBox(-19f, -36f, -44f, 38f, 26f, 33f)   // cab
                        .texOffs(0, 150).addBox(-20f, -10f, -44f, 40f, 4f, 88f)   // chassis
                        .texOffs(144, 90).addBox(-21f, -12f, -46f, 42f, 4f, 2f),  // bumper
                PartPose.offset(0f, 24f, 0f));
        CubeListBuilder wheel = CubeListBuilder.create().texOffs(144, 100).addBox(-2f, -6f, -6f, 4f, 12f, 12f);
        body.addOrReplaceChild("wheel_fl", wheel, PartPose.offset(19f, -6f, -30f));
        body.addOrReplaceChild("wheel_fr", wheel, PartPose.offset(-19f, -6f, -30f));
        body.addOrReplaceChild("wheel_bl", wheel, PartPose.offset(19f, -6f, 30f));
        body.addOrReplaceChild("wheel_br", wheel, PartPose.offset(-19f, -6f, 30f));
        return LayerDefinition.create(mesh, 256, 256);
    }

    @Override
    public void setupAnim(BoxTruckEntity entity, float limbSwing, float limbSwingAmount, float ageInTicks, float netHeadYaw, float headPitch) {
        float spin = limbSwing * 0.8f;
        for (ModelPart w : wheels) w.xRot = spin;
    }

    @Override
    public void renderToBuffer(PoseStack poseStack, VertexConsumer buffer, int light, int overlay, float r, float g, float b, float a) {
        body.render(poseStack, buffer, light, overlay, r, g, b, a);
    }
}
